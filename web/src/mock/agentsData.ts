// Helper to compute canonical edge key: keccak256(min(a,b), max(a,b))
export function computeCanonicalKey(a: number, b: number): string {
  const min = Math.min(a, b);
  const max = Math.max(a, b);
  return `edge_${min}_${max}`;
}

// Generate reciprocal golden handshakes and mesh topology
export function generateInitialEdges(): MeshEdge[] {
  const edges: MeshEdge[] = [];
  const scarlet = INITIAL_AGENTS[0];

  // scarlet.ai is reciprocally connected to all other 35 agents!
  for (let i = 1; i < INITIAL_AGENTS.length; i++) {
    const peer = INITIAL_AGENTS[i];
    edges.push({
      fromTokenId: scarlet.tokenId,
      toTokenId: peer.tokenId,
      fromName: scarlet.name,
      toName: peer.name,
      edgeKey: computeCanonicalKey(scarlet.tokenId, peer.tokenId),
      isMutual: true, // Reciprocal golden handshake
      establishedAt: Date.now() - (i * 3600 * 1000),
      capabilityMask: (scarlet.capabilities & peer.capabilities) || 1,
    });
  }

  // Cross peer-to-peer reciprocal edges for rich cluster mesh
  const peerClusters = [
    [102, 103], [102, 104], [103, 105], [103, 108], [104, 107],
    [106, 114], [106, 117], [108, 115], [108, 119], [111, 116],
    [114, 117], [115, 129], [115, 130], [119, 120], [120, 121],
    [121, 125], [122, 123], [123, 124], [125, 129], [126, 131],
    [127, 134], [128, 133], [129, 130], [130, 132], [131, 136],
    [132, 135], [133, 135]
  ];

  for (const [fromId, toId] of peerClusters) {
    const fromAgent = INITIAL_AGENTS.find(a => a.tokenId === fromId);
    const toAgent = INITIAL_AGENTS.find(a => a.tokenId === toId);
    if (fromAgent && toAgent) {
      edges.push({
        fromTokenId: fromId,
        toTokenId: toId,
        fromName: fromAgent.name,
        toName: toAgent.name,
        edgeKey: computeCanonicalKey(fromId, toId),
        isMutual: true,
        establishedAt: Date.now() - (fromId * 100000),
        capabilityMask: (fromAgent.capabilities & toAgent.capabilities) || 1,
      });
    }
  }

  return edges;
}
